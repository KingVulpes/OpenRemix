#!/usr/bin/env python3
"""Pack the first two dimensions of the Heitz shadow and local-light samplers.

Inputs: src/spp8.rs and src/spp32.rs from Jasper-Bekkers/blue-noise-sampler at
b1720f637a3580c8711580873dcf84cce82f6504 (MIT). Normal builds need no download.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('local_source', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    words = []
    hashes = []
    for path, samples, expected in [
        (args.source, 8, 'd83ac70615014e7ccbc40d394dfb9205eb08b92002822443316d97dbe9c15f78'),
        (args.local_source, 32, '1531d3e0ed13889fb1d3e1a3b9c92a0efde983cc6d0b311ee927ec913bae0949'),
    ]:
        source = path.read_bytes()
        hashes.append(hashlib.sha256(source).hexdigest())
        assert hashes[-1] == expected, 'Unexpected upstream table revision'
        tables = {}
        for name, size in [('SOBOL', 65536), ('SCRAMBLING_TILE', 131072), ('RANKING_TILE', 131072)]:
            match = re.search(r'pub static ' + name + r'.*?= &\[(.*?)\];', source.decode(), re.S)
            values = [int(v) for v in re.findall(r'\d+', match[1])]
            assert len(values) == size and all(0 <= v <= 255 for v in values)
            tables[name] = values
        for pixel in range(128 * 128):
            s = tables['SCRAMBLING_TILE'][pixel * 8:pixel * 8 + 2]
            r = tables['RANKING_TILE'][pixel * 8:pixel * 8 + 2]
            assert max(r) < samples
            words.append(s[0] | s[1] << 8 | r[0] << 16 | r[1] << 24)
        for sample in range(samples):
            words.append(tables['SOBOL'][sample * 256] | tables['SOBOL'][sample * 256 + 1] << 8)
    output = ('// Generated by scripts/shaders/blue_noise.py; do not edit.\n'
              '// Heitz et al. sampler tables via Jasper Bekkers; see LICENSE-blue-noise.txt.\n'
              '// Source SHA-256: ' + ', '.join(hashes) + '\n'
              '#pragma once\n#include <cstdint>\nnamespace remix::trace {\n'
              '// Each table: 128x128 packed scramble/ranking pairs, then packed Sobol pairs.\n'
              'inline constexpr uint32_t blueNoiseSamples[] = {\n')
    for i in range(0, len(words), 8):
        output += '  ' + ', '.join(f'0x{x:08x}' for x in words[i:i + 8]) + ',\n'
    output += '};\n}\n'
    target = ROOT / 'src/native/pathtrace/shaders/blue_noise_data.h'
    if args.check:
        assert target.read_text() == output, 'Blue-noise data differs from source'
    else:
        target.write_text(output)


if __name__ == '__main__':
    main()
